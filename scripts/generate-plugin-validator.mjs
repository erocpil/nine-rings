/** Emit a static ESM validator: package input never becomes executable schema/code. */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standalone from "ajv/dist/standalone/index.js";
const directory = new URL("../schema/plugin/v1/", import.meta.url);
const ajv = new Ajv2020({ allErrors: false, allowUnionTypes: true, code: { source: true, esm: true } });
for (const file of readdirSync(directory).sort()) {
  const schema = JSON.parse(readFileSync(new URL(file, directory), "utf8"));
  if (file === "contributions.schema.json") {
    // The installed interpreter intentionally exposes only paired themes. Do not
    // ship megabytes of validators for unopened commands/properties/queries.
    schema.$defs.Theme = schema.$defs.Theme.oneOf[1];
    schema.$defs.Contributes.properties = { themes: { ...schema.$defs.Contributes.properties.themes, minItems: 1, maxItems: 8 } };
    schema.$defs.Contributes.additionalProperties = false;
  }
  if (file === "manifest.schema.json") {
    schema.properties.entry = false;
    schema.properties.permissions = false;
    schema.properties.activationEvents = false;
  }
  ajv.addSchema(schema);
}
const validator = ajv.getSchema("https://schemas.nine-rings.example/plugin/v1/manifest.strict.schema.json");
let code = standalone(ajv, validator);
const imports = new Map();
code = code.replace(/require\("([^"\n]+)"\)\.default/g, (_, path) => {
  // Only Ajv's known pure runtime helpers are allowed; new dependencies need explicit review.
  if (!["ajv/dist/runtime/ucs2length", "ajv/dist/runtime/equal"].includes(path)) throw Error(`Unknown generated runtime helper: ${path}`);
  if (!imports.has(path)) imports.set(path, `runtime${imports.size}`);
  return imports.get(path);
});
code = "// Generated by scripts/generate-plugin-validator.mjs. Do not edit.\n" + [...imports].map(([path, name]) => `import ${name}Module from "${path}.js";\nconst ${name} = typeof ${name}Module === "function" ? ${name}Module : ${name}Module.default;`).join("\n") + "\n" + code + "\n";
if (/\brequire\s*\(/.test(code)) throw Error("Generated code still requires a runtime loader");
const target = new URL("../src/lib/plugin-system/generated-package-validator.js", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== code) throw Error("Plugin validator is stale; run node scripts/generate-plugin-validator.mjs");
  console.log("Static plugin validator matches reviewed schemas");
} else {
  writeFileSync(target, code);
  console.log(`Generated ${fileURLToPath(target)} (${Buffer.byteLength(code)} bytes)`);
}
