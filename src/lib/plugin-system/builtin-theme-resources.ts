import { validateThemeResource, type ThemeColors } from "./theme-resources";

export const THEME_PLUGIN_ID = "nine-rings.builtin-theme";
type BaseColors = Omit<
  ThemeColors,
  "syntaxKeyword" | "syntaxString" | "syntaxValue" | "syntaxMeta" | "syntaxType"
>;
// Resolve the host's existing sRGB syntax roles into serializable color values.
function syntax(colors: BaseColors, dark: boolean): ThemeColors {
  const mix = (first: string, second: string, fraction: number) =>
    "#" +
    [1, 3, 5]
      .map((index) =>
        Math.round(
          parseInt(first.slice(index, index + 2), 16) * fraction +
            parseInt(second.slice(index, index + 2), 16) * (1 - fraction),
        )
          .toString(16)
          .padStart(2, "0"),
      )
      .join("");
  return {
    ...colors,
    syntaxKeyword: mix(dark ? "#f85149" : "#cf222e", colors.text, 0.82),
    syntaxString: mix(dark ? "#3fb950" : "#1a7f37", colors.text, 0.82),
    syntaxValue: mix(colors.accent, colors.text, 0.86),
    syntaxMeta: mix("#b45f06", colors.text, 0.82),
    syntaxType: mix(colors.accent, colors.text, 0.78),
  };
}
function standard(
  id: string,
  name: string,
  light: BaseColors,
  dark: BaseColors,
) {
  return validateThemeResource({
    version: 1,
    id: `${THEME_PLUGIN_ID}/${id}`,
    name,
    light: syntax(light, false),
    dark: syntax(dark, true),
    typography: {
      headingScale: [1.75, 1.5, 1.375, 1.25, 1.125, 1],
      compactHeadingScale: [1.625, 1.5, 1.375, 1.25, 1.125, 1],
      codeFont: "monospace",
      quoteFont: "system",
      flowFont: "system",
    },
  });
}
