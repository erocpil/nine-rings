import { expect, test } from "@playwright/test";
import { createBlankDocument } from "./helpers/document";
import { replaceSource, selectDocumentLanguage, sourceInfo } from "./helpers/source-editor";

test("相同行按段展开和收起，保持双侧可视位置并支持键盘与全部开关", async ({ page }) => {
  test.setTimeout(90000);
  await page.setViewportSize({ width: 1000, height: 700 });
  await createBlankDocument(page, "差异逐段折叠位置");
  await selectDocumentLanguage(page, "c");
  const area = page.locator(".cm-content");
  const comments = (prefix: string, length: number) => Array.from({ length }, (_, index) => `// ${prefix} unchanged ${index + 1}`);
  const raw = [...comments("first", 50), "int first=1;", ...comments("middle", 70),
    ...Array.from({ length: 45 }, (_, index) => `int tail${index}=${index};`), ...comments("last", 40)].join("\n");
  await replaceSource(area, raw);
  await page.getByRole("button", { name: "格式化全文", exact: true }).click();
  await page.locator(".source-indent-toast").getByRole("button", { name: "查看差异", exact: true }).click({ timeout: 60000 });
  const dialog = page.getByRole("dialog", { name: "格式化差异", exact: true });
  const panes = dialog.locator(".document-diff-scroll-pane");
  const left = panes.first();
  const right = panes.last();
  const showAll = dialog.getByRole("checkbox", { name: "显示相同行", exact: true });
  await expect(left.locator(".document-diff-collapsed")).toHaveCount(3);
  const firstChange = left.locator(".document-diff-line.removed").first();
  const firstChangeY = (await firstChange.boundingBox())!.y;
  await showAll.check();
  await expect.poll(async () => Math.abs((await firstChange.boundingBox())!.y - firstChangeY)).toBeLessThan(2);
  await showAll.uncheck();
  await expect.poll(async () => Math.abs((await firstChange.boundingBox())!.y - firstChangeY)).toBeLessThan(2);
  await left.getByRole("button", { name: "展开 50 行相同内容", exact: true }).click();
  await expect.poll(async () => Math.abs((await firstChange.boundingBox())!.y - firstChangeY)).toBeLessThan(2);
  expect(await left.evaluate(element => element.scrollTop)).toBeGreaterThan(500);
  await expect(left.locator(".document-diff-collapsed")).toHaveCount(2);
  await expect(right.locator(".document-diff-same-collapse")).toHaveCount(1);
  expect(await showAll.evaluate(element => (element as HTMLInputElement).indeterminate)).toBe(true);

  const middle = left.getByRole("button", { name: "展开 70 行相同内容", exact: true });
  await middle.scrollIntoViewIfNeeded();
  const followingChange = left.locator(".document-diff-line.removed").nth(1);
  const topBefore = (await followingChange.boundingBox())!.y;
  await middle.click();
  const group = left.locator(".document-diff-same-group").filter({ hasText: "// middle unchanged 1" });
  await expect.poll(async () => Math.abs((await followingChange.boundingBox())!.y - topBefore)).toBeLessThan(2);
  await group.evaluate(element => {
    const pane = element.closest<HTMLElement>(".document-diff-scroll-pane")!;
    pane.scrollTop += element.getBoundingClientRect().top - pane.getBoundingClientRect().top + 350;
  });
  await expect.poll(async () => Math.abs(await left.evaluate(el => el.scrollTop) - await right.evaluate(el => el.scrollTop))).toBeLessThan(2);
  const paneBox = (await left.boundingBox())!;
  const rail = group.getByRole("button", { name: "收起 70 行相同内容", exact: true });
  const railBox = (await rail.boundingBox())!;
  const hit = await page.evaluate(({ x, y }) => document.elementFromPoint(x, y)?.outerHTML, { x: railBox.x + railBox.width / 2, y: paneBox.y + 70 });
  expect(hit).toContain("document-diff-same-collapse");
  // Click the rail in the visible middle of a long group, without scrolling its
  // first row back into view as locator.click() would do for a large button.
  await page.mouse.click(railBox.x + railBox.width / 2, paneBox.y + 70);
  await expect(left.locator(".document-diff-same-collapse")).toHaveCount(1);
  await expect(right.locator(".document-diff-same-collapse")).toHaveCount(1);
  const folded = left.getByRole("button", { name: "展开 70 行相同内容", exact: true });
  await expect.poll(async () => Math.abs((await folded.boundingBox())!.y - paneBox.y)).toBeLessThan(3);
  expect(await left.evaluate(element => element.scrollTop)).toBeGreaterThan(500);
  await expect.poll(async () => Math.abs(await left.evaluate(el => el.scrollTop) - await right.evaluate(el => el.scrollTop))).toBeLessThan(2);

  await folded.click();
  const changeYBeforeCollapse = (await followingChange.boundingBox())!.y;
  const expandedRail = (await group.locator(".document-diff-same-collapse").boundingBox())!;
  await page.mouse.click(expandedRail.x + expandedRail.width / 2, changeYBeforeCollapse - 8);
  await expect(folded).toBeVisible();
  await expect.poll(async () => Math.abs((await followingChange.boundingBox())!.y - changeYBeforeCollapse)).toBeLessThan(2);

  await showAll.check();
  await expect(left.locator(".document-diff-same-collapse")).toHaveCount(3);
  const keyboardRail = left.getByRole("button", { name: "收起 70 行相同内容", exact: true });
  await keyboardRail.focus();
  await page.keyboard.press("Space");
  await expect(folded).toBeFocused();
  expect(await showAll.evaluate(element => (element as HTMLInputElement).indeterminate)).toBe(true);
  await showAll.check();
  await showAll.uncheck();
  await expect(left.locator(".document-diff-same-collapse")).toHaveCount(0);
  await expect(left.locator(".document-diff-collapsed")).toHaveCount(3);
  await page.keyboard.press("Escape");
  await expect(dialog).toHaveCount(0);
  await page.getByRole("toolbar", { name: "源码编辑工具" }).getByRole("button", { name: "撤销", exact: true }).click();
  await expect.poll(async () => (await sourceInfo(area)).value).toBe(raw);
});

test("格式化差异保留原始代码，支持相同行折叠和过期快照说明，不影响撤销", async ({ page }) => {
  await createBlankDocument(page, "格式化差异甲");
  await selectDocumentLanguage(page, "c");
  const area = page.getByRole("textbox", { name: "C/C++ 源码", exact: true });
  const toolbar = page.getByRole("toolbar", { name: "源码编辑工具" });
  const history = toolbar.getByRole("button", { name: "查看上次格式化差异", exact: true });
  await expect(history).toBeDisabled();
  const raw = '// 原样保留 ** [x] <tag>\n// second comment\nint main(){\nint value=1;\nreturn value;\n}';
  await replaceSource(area, raw);
  await toolbar.getByRole("button", { name: "格式化全文", exact: true }).click();
  const toast = page.locator(".source-indent-toast");
  await toast.getByRole("button", { name: "查看差异", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "格式化差异", exact: true });
  await expect(dialog).toBeVisible();
  const closeButton = dialog.getByRole("button", { name: "关闭格式化差异", exact: true });
  expect(await closeButton.evaluate(button => document.activeElement === button)).toBe(false);
  await page.keyboard.press("Escape");
  await expect(dialog).toHaveCount(0);
  await history.click();
  await expect(dialog).toBeVisible();
  await expect(dialog).toContainText("当前源码与上次格式化结果一致");
  const panes = dialog.locator(".document-diff-scroll-pane");
  await expect(panes.nth(0)).toContainText("int value=1;");
  await expect(panes.nth(1)).toContainText("int value = 1;");
  await dialog.locator(".document-diff-collapsed").first().click();
  await expect(panes.nth(0)).toContainText("** [x] <tag>");
  await expect(dialog.getByRole("checkbox", { name: "显示相同行", exact: true })).toBeChecked();
  const formatted = (await sourceInfo(area)).value;
  const whitespaceToggle = dialog.getByRole("button", { name: "显示不可见字符", exact: true });
  await whitespaceToggle.hover();
  const tooltip = page.getByRole("tooltip");
  await expect(tooltip).toBeVisible();
  const tooltipGap = await whitespaceToggle.evaluate(button => document.querySelector('[role="tooltip"]')!.getBoundingClientRect().top - button.getBoundingClientRect().bottom);
  expect(tooltipGap).toBeGreaterThanOrEqual(4);
  expect(tooltipGap).toBeLessThanOrEqual(8);
  await whitespaceToggle.click();
  await expect(dialog.getByRole("button", { name: "隐藏不可见字符", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(panes.first().locator(".diff-whitespace-space").first()).toBeVisible();
  expect((await sourceInfo(area)).value).toBe(formatted);
  await page.keyboard.press("Escape");
  await expect(dialog).toHaveCount(0);
  expect((await sourceInfo(area)).value).toBe(formatted);
  await toolbar.getByRole("button", { name: "撤销", exact: true }).click();
  await expect.poll(async () => (await sourceInfo(area)).value).toBe(raw);
  await history.click();
  await expect(dialog).toContainText("源码在上次格式化后已修改；下方仍是上次格式化记录。若要查看当前格式化效果，请重新执行格式化。");
  await expect(dialog.locator(".document-diff-scroll-pane").nth(1)).toContainText("int value = 1;");
  await dialog.getByRole("button", { name: "关闭格式化差异", exact: true }).click();
  await expect(dialog).toHaveCount(0);
});

test("格式化快照按文档隔离，长代码对比同步滚动且标题固定", async ({ page }) => {
  await page.setViewportSize({ width: 1000, height: 700 });
  await createBlankDocument(page, "格式化快照甲");
  const first = await page.evaluate(() => localStorage.getItem("nr:lastNote"));
  await selectDocumentLanguage(page, "c");
  const area = page.getByRole("textbox", { name: "C/C++ 源码", exact: true });
  const raw = `void test(){\n${Array.from({ length: 150 }, (_, n) => `int value${n}=${n}; // ${"long text ".repeat(20)}`).join("\n")}\n}`;
  await replaceSource(area, raw);
  await page.getByRole("button", { name: "格式化全文", exact: true }).click();
  await expect(page.getByRole("button", { name: "查看上次格式化差异", exact: true })).toBeEnabled();
  await page.getByRole("button", { name: "新建文档", exact: true }).click();
  await page.getByPlaceholder("文档标题...").fill("格式化快照乙");
  await page.getByRole("button", { name: "创建", exact: true }).click();
  await expect.poll(() => page.evaluate(() => localStorage.getItem("nr:lastNote"))).not.toBe(first);
  await selectDocumentLanguage(page, "c");
  const history = page.getByRole("button", { name: "查看上次格式化差异", exact: true });
  await expect(history).toBeDisabled();
  await page.getByRole("button", { name: "格式化快照甲", exact: true }).click();
  await expect(history).toBeEnabled();
  await history.click();
  const dialog = page.getByRole("dialog", { name: "格式化差异", exact: true });
  await expect(dialog).toBeVisible();
  const panes = dialog.locator(".document-diff-scroll-pane");
  await panes.first().hover();
  // Stay inside the horizontal range shared by both sides (formatting wraps
  // long comments, so their maximum horizontal extents intentionally differ).
  await page.mouse.wheel(80, 350);
  await expect.poll(() => panes.first().evaluate(element => element.scrollTop)).toBeGreaterThan(0);
  await expect.poll(async () => Math.abs(await panes.first().evaluate(element => element.scrollTop) - await panes.last().evaluate(element => element.scrollTop))).toBeLessThan(2);
  await expect.poll(() => panes.first().evaluate(element => element.scrollLeft)).toBeGreaterThan(0);
  await expect.poll(async () => Math.abs(await panes.first().evaluate(element => element.scrollLeft) - await panes.last().evaluate(element => element.scrollLeft))).toBeLessThan(2);
  await panes.last().hover();
  await page.mouse.wheel(-35, 120);
  await expect.poll(() => panes.last().evaluate(element => element.scrollLeft)).toBeLessThan(80);
  await expect.poll(async () => Math.abs(await panes.first().evaluate(element => element.scrollLeft) - await panes.last().evaluate(element => element.scrollLeft))).toBeLessThan(2);
  await expect.poll(async () => Math.abs(await panes.first().evaluate(element => element.scrollTop) - await panes.last().evaluate(element => element.scrollTop))).toBeLessThan(2);
  await expect(dialog.getByRole("heading", { name: "格式化差异", exact: true })).toBeInViewport();
  await expect(dialog.getByRole("button", { name: "关闭格式化差异", exact: true })).toBeInViewport();
});

test("格式化差异中的 Tab 宽度与源码编辑区状态栏设置一致", async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem("nr:blockWorkspaceDisplay", JSON.stringify({ tabSize: 8 }));
  });
  await createBlankDocument(page, "格式化差异 Tab 宽度");
  await selectDocumentLanguage(page, "c");
  const area = page.getByRole("textbox", { name: "C/C++ 源码", exact: true });
  await replaceSource(area, "void f(){\n\treturn;\n}");
  const editorTabSize = await page.locator(".cm-content").evaluate(element => getComputedStyle(element).tabSize);
  expect(editorTabSize).toBe("8");
  await page.getByRole("button", { name: "格式化全文", exact: true }).click();
  await page.locator(".source-indent-toast").getByRole("button", { name: "查看差异", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "格式化差异", exact: true });
  const diffTabSize = await dialog.locator(".document-diff-line code").first().evaluate(element => getComputedStyle(element).tabSize);
  expect(diffTabSize).toBe(editorTabSize);
  await page.keyboard.press("Escape");
  await expect(dialog).toHaveCount(0);
});
